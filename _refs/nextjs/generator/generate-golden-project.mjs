import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const profileFeatures = Object.freeze({
  basic: ['init-site', 'theme', 'pages', 'responsive'],
  i18n: ['init-site', 'theme', 'pages', 'responsive', 'i18n'],
  contact: ['init-site', 'theme', 'pages', 'responsive', 'contact-form'],
});

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function packageFile(profile) {
  const dependencies = {
    next: '16.2.12',
    react: '19.2.8',
    'react-dom': '19.2.8',
  };
  if (profile === 'i18n') dependencies['next-intl'] = '4.13.4';
  if (profile === 'contact') dependencies.zod = '4.4.3';
  return json({
    name: `sdcorejs-nextjs-golden-${profile}`,
    version: '0.0.0',
    private: true,
    scripts: {
      typecheck: 'tsc --noEmit',
      test: 'node --test test/*.test.mjs',
      build: 'next build',
    },
    dependencies,
    devDependencies: {
      '@types/node': '24.10.9',
      '@types/react': '19.2.14',
      '@types/react-dom': '19.2.3',
      typescript: '5.9.3',
    },
  });
}

