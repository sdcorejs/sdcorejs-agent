function contactFiles() {
  return {
    'src/lib/contact-core.mjs': `/**
 * @param {Headers} headers
 */
export function clientIp(headers) {
  const forwarded = headers.get('x-forwarded-for');
  return forwarded?.split(',')[0]?.trim() || headers.get('x-real-ip')?.trim() || 'unknown';
}

/**
 * @param {Headers} headers
 */
export function requestLocale(headers) {
  const value = headers.get('accept-language')?.split(',')[0]?.trim().toLowerCase() || 'en';
  return value.split('-')[0] || 'en';
}
`,
    'src/lib/contact-schema.ts': `import { z } from 'zod';

export const contactSchema = z.object({
  name: z.string().trim().min(2).max(100),
  email: z.email().max(254),
  message: z.string().trim().min(10).max(5_000),
});
`,
    'src/app/api/contact/route.ts': `import { NextResponse } from 'next/server';
import { clientIp, requestLocale } from '@/lib/contact-core.mjs';
import { contactSchema } from '@/lib/contact-schema';

export async function POST(request: Request) {
  const parsed = contactSchema.safeParse(await request.json());
  if (!parsed.success) {
    return NextResponse.json({ ok: false, code: 'invalid_request' }, { status: 400 });
  }

  const webhook = process.env.CONTACT_WEBHOOK_URL;
  if (!webhook) {
    return NextResponse.json({ ok: false, code: 'provider_not_configured' }, { status: 503 });
  }

  const response = await fetch(webhook, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      ...parsed.data,
      clientIp: clientIp(request.headers),
      locale: requestLocale(request.headers),
    }),
  });
  if (!response.ok) {
    return NextResponse.json({ ok: false, code: 'provider_failed' }, { status: 502 });
  }
  return NextResponse.json({ ok: true }, { status: 202 });
}
`,
    'test/contact.test.mjs': `import assert from 'node:assert/strict';
import test from 'node:test';
import { clientIp, requestLocale } from '../src/lib/contact-core.mjs';

test('contact boundary normalizes forwarded IP and locale headers', () => {
  const headers = new Headers({
    'x-forwarded-for': ' 203.0.113.7, 10.0.0.2 ',
    'accept-language': 'vi-VN,vi;q=0.9,en;q=0.8',
  });
  assert.equal(clientIp(headers), '203.0.113.7');
  assert.equal(requestLocale(headers), 'vi');
});

test('contact boundary has honest fallbacks', () => {
  assert.equal(clientIp(new Headers()), 'unknown');
  assert.equal(requestLocale(new Headers()), 'en');
});
`,
  };
}

export async function generateNextjsGoldenProject({ output, outputRoot, profile }) {
  if (!Object.hasOwn(profileFeatures, profile)) {
    throw new Error(`Unknown Next.js golden profile: ${profile}`);
  }
  const resolvedRoot = path.resolve(outputRoot);
  const resolvedOutput = path.resolve(output);
  const relative = path.relative(resolvedRoot, resolvedOutput);
  if (
    relative === '' ||
    relative === '..' ||
    relative.startsWith(`..${path.sep}`) ||
    path.isAbsolute(relative)
  ) {
    throw new Error('Next.js golden output must be a strict child inside outputRoot.');
  }

  const files = {
    ...baseFiles(profile),
    ...(profile === 'i18n' ? i18nFiles() : {}),
    ...(profile === 'contact' ? contactFiles() : {}),
  };
  try {
    await mkdir(resolvedOutput, { recursive: false });
  } catch (error) {
    if (error?.code === 'EEXIST') {
      throw new Error('Next.js golden output already exists; overwrite is denied.');
    }
    throw error;
  }
  for (const [relativePath, source] of Object.entries(files)) {
    const target = path.join(resolvedOutput, relativePath);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, source, { encoding: 'utf8', flag: 'wx' });
  }
  return {
    fixture_kind: 'generated-real-nextjs',
    next_version: '16.2.12',
    profile,
    approved_features: profileFeatures[profile],
    files: Object.keys(files).sort(),
  };
}
